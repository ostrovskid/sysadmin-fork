#!/usr/bin/env bash
# .claude/hooks/red-zone-guard.sh — PreToolUse-хук: замок красной зоны (ADR-0022).
#
# ЗАЧЕМ. Конституция §6.3/C.3 требует type-to-confirm перед необратимой операцией.
# До этого хука правило держалось ТОЛЬКО на добросовестности агента: проза в CLAUDE.md —
# табличка «не входить», а не замок. Хук превращает её в принуждение: команда красной
# зоны не выполнится, пока ОПЕРАТОР не написал фразу подтверждения своими руками.
#
# ПОЧЕМУ ЭТО НЕЛЬЗЯ ОБОЙТИ АГЕНТУ. Подтверждение ищется в сообщениях роли `user`
# реального транскрипта сессии. Агент пишет только сообщения роли `assistant` —
# сочинить себе разрешение он физически не может.
#
# ПОВЕДЕНИЕ:
#   команда не из красной зоны        → тихо пропускаем (exit 0)
#   красная зона + фраза оператора    → пропускаем
#   красная зона без фразы            → deny + инструкция, что написать
#   не смогли проверить транскрипт    → deny (fail-closed: молчаливый пропуск опаснее)
#   python3 нет или он сломан         → deny запасным текстом через printf (см. deny)
#   не успели проверить команду       → deny (fail-closed, см. HOOK_BUDGET и сторож времени
#                                        в конце файла: бюджет покрывает ВЕСЬ замок)
#
# Настраивается в .claude/settings.json (event PreToolUse, matcher Bash). Таймаут там
# (15 с) обязан быть больше HOOK_BUDGET: хук, прерванный движком, — это «разрешаю».
# Ручная проверка: bash .claude/hooks/tests/test-red-zone-guard.sh

set -uo pipefail

# Вывод хука читает движок, а не терминал: печатаем UTF-8 независимо от кодовой страницы
# консоли. Без этого на Windows (cp1252) python падает на первом же не-ASCII символе, а
# сообщения здесь русские — хук не печатает НИЧЕГО и выходит с кодом 0, что движок читает
# как «разрешаю»: замок молча пропускает то, ради чего поставлен (поймано 26.08.2026,
# 16 случаев теста из 16). Разбор — building-enforcement.md, правило «немой замок».
export PYTHONIOENCODING=utf-8

# Вход (stdin) читается не здесь, а внутри проверки под сторожем времени — `proverit` ниже:
# даже `cat` — порождённый процесс, а до сторожа время не считается никем.

# ── Фраза подтверждения (канон C.3) ───────────────────────────────────────────
# Ищем скелет: «беру риск на себя» + «бэкап проверен» (е/ё и регистр — свободно).
# Полная форма: «подтверждаю <операция>, беру риск на себя, бэкап проверен».
CONFIRM_RE='беру риск на себя'
CONFIRM_RE2='б[эеёЭЕЁ]кап проверен'
# Окно свежести: подтверждение действительно N последних реплик оператора,
# иначе одна фраза открывала бы дверь до конца сессии.
CONFIRM_WINDOW=10

# ── Паттерны красной зоны (§6.3 CLAUDE.md) ────────────────────────────────────
# Расширенные regex, регистронезависимо. Ловим и обёртки вида ssh host "…".
RED_PATTERNS=(
  'rm[[:space:]]+(-[a-zA-Z]*[rR][a-zA-Z]*[fF]|-[a-zA-Z]*[fF][a-zA-Z]*[rR])'
  # Рекурсивное удаление в ЛЮБОЙ записи ключей. Шаблон выше ловит только склеенные `-rf`/`-fr`;
  # раздельные (`-r -f`), длинные (`--recursive --force`) и `-r` без `-f` (тоже необратимо)
  # проходили мимо замка — проба 19.10.2026. Сравнение — по нижнему регистру: `-R` = `-r`.
  # `git rm` без ключа силы снят отдельно, см. GIT_RM_LEAD.
  '(^|[^a-z0-9_.-])rm[[:space:]]+([^[:space:]]+[[:space:]]+)*(-[a-z]*r[a-z]*|--recursive)([[:space:]]|$)'
  # Массовое удаление без ключа рекурсии: обход дерева делает find, а не rm (`find … -delete`,
  # `find … -exec rm {} +`), или имена приходят в xargs (красная команда 19.10).
  '(^|[^a-z0-9_.-])find[[:space:]].*(-delete|-exec(dir)?[[:space:]]+(/usr)?(/bin/)?(rm|unlink|shred)([[:space:]]|$))'
  '(^|[^a-z0-9_.-])xargs([[:space:]]+[^[:space:]]+)*[[:space:]]+(/usr)?(/bin/)?(rm|unlink|shred)([[:space:]]|$)'
  'drop[[:space:]]+(database|table|schema)'
  # Группа обязательна: без неё ловилась ЛЮБАЯ команда со словом truncate —
  # `truncate -s 0 /var/log/app.log` (штатная ротация) и даже `grep truncate`.
  'truncate[[:space:]]+(table|only)'
  'docker[[:space:]]+volume[[:space:]]+(rm|prune)'
  'docker[[:space:]]+system[[:space:]]+prune'
  # Ключ силы — отдельным словом (`-f`, склейка `-uf`, `--force`, `--force-with-lease`) или
  # «+» перед веткой (`git push origin +main` — тоже принудительная перезапись). Прежний
  # хвост `-f$` ловил имя ветки на «-f» (`release-f`) — ложный блок (красная команда 19.10).
  'git[[:space:]]+push[[:space:]](.*[[:space:]])?(--force[a-z-]*|-[a-z]*f[a-z]*|\+[^[:space:]]+)([[:space:]=]|$)'
  'git[[:space:]]+reset[[:space:]]+--hard'
  '(userdel|deluser)[[:space:]]'
  'ufw[[:space:]]+(reset|disable)'
  'mkfs(\.[a-z0-9]+)?[[:space:]]'
  'dd[[:space:]]+.*of=/dev/'
  '>[[:space:]]*/etc/ssh/sshd_config'
  'sed[[:space:]]+-i.*sshd_config'
)

# Исключения: временные каталоги — снос там обратим по смыслу и не трогает прод.
#
# Имя переменной пишем СТРОЧНЫМИ: сравнение идёт по команде, приведённой к нижнему
# регистру (LOWER ниже), поэтому шаблон `TMPDIR` заглавными не совпадал никогда —
# уборка агентом собственного временного каталога через `$TMPDIR` ложно уходила в
# красную зону и дёргала оператора ритуалом (ADR-0038 говорит обратное).
#
# Windows-ветка: временный каталог агента там — `…/AppData/Local/Temp/…`, а не /tmp,
# поэтому на Windows исключение не срабатывало вовсе. Ловим обе формы записи пути:
# нативную `C:\Users\…` и msys-форму `/c/users/…`.
#
# Ограничитель прежний и главный — PROD_PATH_RE ниже: упомянут боевой каталог в том же
# сегменте, и исключение не действует, каким бы временным путём команда ни начиналась.
#
# Знак $ перед именем переменной ОБЯЗАТЕЛЕН. С необязательным `\$?` шаблон разрешал и
# голое слово: `rm -rf temp` в текущем каталоге — то есть чей угодно рабочий каталог
# с таким именем — проходил как «уборка временного». Найдено пробой 19.08.2026.
#
# Граница после имени переменной — явным классом, а не `\b`: разбор идёт встроенным `=~`
# bash, то есть системной библиотекой регулярных выражений, а `\b` в POSIX ERE не входит
# (GNU и Cygwin его понимают, BSD-библиотека macOS — не обязана). Молча несовпавший шаблон
# исключения превратил бы уборку своего временного в ложную красную зону.
#
# Ключи перед путём — любой записью и в любом числе (`-rf`, `-r -f`, `--recursive`) и знак
# конца ключей `--`: `rm -rf -- "$dir"` — штатная защитная запись, её же даёт образец
# ADR-0038. Без этого уборка своего временного с `--` ложно уходила в красную зону
# (найдено 19.10.2026). Шаблон — лишь первый фильтр: исключение действует, только если
# ВСЕ пути этого rm временные (разбор по словам в цикле ниже, TEMP_PATH_RE).
SAFE_RM_RE='rm([[:space:]]+-[^[:space:]]*)+[[:space:]]+("?(/private)?/(tmp|var/tmp)/|"?\$\{?(tmpdir|temp|tmp)([^a-z0-9_]|$)|"?([a-z]:|/[a-z])[\\/]+users[\\/]+[^\\/[:space:]]+[\\/]+appdata[\\/]+local[\\/]+temp)'
# Проверка КАЖДОГО пути у rm. Прежнее исключение смотрело только на первый путь: команда,
# начатая со временного каталога, уносила вторым путём что угодно вне списка боевых —
# домашний каталог, «Документы», `$HOME` (проба 19.10.2026). Теперь слово за словом:
# ключи (`-…`, в том числе `--`) и перенаправления (`2>/dev/null`) пропускаются, каждый
# остальной аргумент обязан начинаться во временном каталоге, хотя бы один путь — обязателен.
# Слово — строка в двойных кавычках или кусок без пробелов; одинарные кавычки и хвостовая
# кавычка обёртки `ssh host "…"` снимаются. Путь в одинарных кавычках с пробелом рвётся на
# куски и уходит в красную зону — ложный отказ дешевле ложного пропуска.
TOKEN_RE='^[[:space:]]*("[^"]*"|[^[:space:]]+)'
# Перенаправление внутри «временной» команды: ввод (`<`) безопасен, вывод (`>`, `>>`) — только в
# дескриптор (`2>&1`), в /dev/null или во временный каталог. Иначе `rm -rf /tmp/x >~/.bashrc`
# проходил исключением и обнулял чужой файл (красная команда 19.10). Цель — прилепленная к
# знаку или следующим словом.
REDIR_RE='^[0-9]*(<|>>?)'
SAFE_REDIR_RE='^(&[0-9]+|&-|/dev/null)$'
# Переменная — временная, только в форме `$TMPDIR…` или `${TMPDIR}`/`${TMPDIR:?…}`. Формы
# с подстановкой (`${TMPDIR:-$HOME}`, `${TMP:+/home/x}`) отдают чужой путь, когда переменная
# не задана или задана, — прежний шаблон `\$\{?tmpdir…` их принимал (проба 19.10.2026).
TEMP_PATH_RE='^((/private)?/(tmp|var/tmp)/|\$(tmpdir|temp|tmp)([^a-z0-9_{]|$)|\$\{(tmpdir|temp|tmp)(:?\?[^}]*)?\}|([a-z]:|/[a-z])[\\/]+users[\\/]+[^\\/]+[\\/]+appdata[\\/]+local[\\/]+temp([\\/]|$))'
# Команда, которая сама задаёт эти переменные (`TMP=~; rm -rf "$TMP"`, `read TMP`,
# `export TMPDIR=…`), лишает их доверия: путь в форме переменной тогда не считается
# временным. Признак — имя отдельным словом, не после `$`/`{` и не частью пути (`/tmp`,
# `…\Temp`, `mktemp`). Ложный отказ (`echo tmp; rm -rf "$TMPDIR/x"`) — осознанная цена.
TMPVAR_WORD_RE='(^|[^a-z0-9_${/.\\-])(tmpdir|temp|tmp)([^a-z0-9_]|$)'
# `git rm` без ключа силы — не красная зона: удаляет только файлы под git, вернуть их —
# `git checkout`, а файл с незафиксированными правками git без `-f` удалять отказывается.
# С `-f`/`--force` — красная зона (теряются незафиксированные правки). Подстановка команды
# в сегменте снимает послабление: внутри `$(…)` может стоять что угодно.
GIT_RM_LEAD='^git[[:space:]]+rm[[:space:]]'
FORCE_OPT_RE='(^|[[:space:]])(-[a-z]*f[a-z]*|--force)([[:space:]]|$)'
# Подстановка процесса `<(…)` и `>(…)` исполняет вложенную команду так же, как `$(…)`: `cat <(…)`
# с удалением внутри проходил пропуском по read-only началу (красная команда 19.10).
SUBST_RE='\$\(|`|[<>]\('
# Имя команды удаления в переменной (`X=rm; $X -rf /opt`, `C=rm; eval "$C …"`): замок не
# раскрывает переменные, поэтому само присваивание такого имени — красная зона. Проверяется
# по тексту без кавычек и обратных косых (LNORM).
RM_VAR_RE='(^|[^a-z0-9_])[a-z_][a-z0-9_]*=(/usr)?(/bin/)?(rm|unlink|shred)([[:space:];&|)]|$)'
# Выход вверх по дереву (`..`) отменяет исключение целиком: путь начинается во временном
# каталоге, а заканчивается где угодно. Снос домашнего каталога через `/tmp/../Users/...`
# замок пропускал ещё ДО PR #11 — дыра жила в ветке /tmp с самого начала и вскрылась
# только на пробе противоположными случаями 19.08.2026. Список боевых каталогов её не
# закрывает: домашние каталоги, рабочие папки и диск Windows в него не входят.
TRAVERSAL_RE='(^|[[:space:]"/\\])\.\.([/\\]|$)'
# Боевые каталоги: встретился в ТОМ ЖЕ сегменте — исключение не действует
# (кейс `rm -rf /tmp/x /opt/prod`). Проверяется посегментно, см. цикл ниже.
#
# Начало пути обязано быть настоящим началом: перед ним не буква, не цифра, не дефис и не
# подчёркивание. Без этой границы `/tmp/data-dump` читался как боевой `/data`, а `/tmp/../opt`
# — наоборот, проскакивал бы, если бы границу задали только пробелом и кавычкой.
PROD_PATH_RE='(^|[^a-zA-Z0-9_-])(/opt|/etc|/var/lib|/var/www|/home|/root|/srv|/data|/usr)'

# ── Извлечение команды из stdin ───────────────────────────────────────────────
# python3 → jq → грубый фолбэк по сырому тексту (Windows без jq — реальный кейс).
json_get() { # $1 = путь вида tool_input.command
  local path="$1"
  if command -v python3 >/dev/null 2>&1; then
    printf '%s' "$RAW" | python3 -c '
import sys, json
try:
    d = json.load(sys.stdin)
except Exception:
    sys.exit(1)
cur = d
for k in sys.argv[1].split("."):
    if not isinstance(cur, dict) or k not in cur:
        sys.exit(1)
    cur = cur[k]
print(cur if isinstance(cur, str) else json.dumps(cur))
' "$path" 2>/dev/null && return 0
  fi
  if command -v jq >/dev/null 2>&1; then
    printf '%s' "$RAW" | jq -er ".${path} // empty" 2>/dev/null && return 0
  fi
  return 1
}

deny() { # $1 = причина для агента и оператора
  local reason="$1" out=""
  if command -v python3 >/dev/null 2>&1; then
    out="$(python3 -c '
import sys, json
print(json.dumps({
  "hookSpecificOutput": {
    "hookEventName": "PreToolUse",
    "permissionDecision": "deny",
    "permissionDecisionReason": sys.argv[1],
  }
}, ensure_ascii=False))
' "$reason" 2>/dev/null)"
  fi
  if [[ "$out" == *'"permissionDecision": "deny"'* ]]; then
    printf '%s\n' "$out"
    exit 0
  fi
  # python3 нет — или он есть, но сломан. На Windows `python3` часто заглушка Microsoft
  # Store: без установленного Python она сразу падает с подсказкой «install from the
  # Store». Раньше отказ в этом случае не печатался вовсе, замок молчал с кодом 0, и
  # движок пропускал даже `docker volume rm` (найдено 06.10.2026 подставным python3).
  # Печатаем отказ встроенным printf, без повтора команды: надёжно экранировать
  # произвольный текст для JSON без python нечем, а лишний отказ безопаснее немого замка.
  printf '%s\n' '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"🔴 ЗАМОК КРАСНОЙ ЗОНЫ заблокировал команду (fail-closed). Подробный вердикт напечатать нечем: python3 недоступен или сломан (на Windows — заглушка Microsoft Store без Python?), поэтому подтверждение оператора проверить нельзя.\nАгент: если команда необратима — пройди §6.3 и попроси оператора написать СВОИМИ РУКАМИ: подтверждаю <что именно делаем>, беру риск на себя, бэкап проверен. Если команда безопасна или фраза уже есть — почини python3 и повтори."}}'
  exit 0
}

# ── Красная зона? ─────────────────────────────────────────────────────────────
# Команда разбирается ПО СЕГМЕНТАМ (`;` `&&` `||` `|` перевод строки), и сегменты,
# начинающиеся с read-only утилиты, пропускаются целиком: их аргументы — данные, а не
# команды. Без этого `grep -rn "rm -rf" scripts/` и `grep truncate nginx.conf` блокировались
# как красная зона — три холостых срабатывания за день (разбор сессии 2026-07-24, F4/F4+).
#
# ВАЖНО: пропускаем ТОЛЬКО read-only лидеров. Сегмент `ssh host "rm -rf /opt"` начинается с
# ssh — не read-only, поэтому опасное содержимое кавычек по-прежнему ловится (это главный
# способ, которым агент трогает сервер).
READONLY_LEAD='^(grep|egrep|fgrep|rg|ag|echo|printf|cat|bat|less|more|head|tail|wc|jq|yq|sort|uniq|column|diff|comm|man|which|type|file|stat|basename|dirname)([[:space:]]|$)'
# Git-подкоманды, чьи аргументы — текст, а не операция: сообщение коммита или тега
# запросто содержит «rm -rf» как цитату (поймало на четвёртом холостом срабатывании
# в самой сессии разбора). Опасные подкоманды сюда НЕ входят: `git push --force`,
# `git reset --hard` остаются в RED_PATTERNS. Цепочка проверяется посегментно, поэтому
# `git commit -m "…" && rm -rf /opt` всё равно блокируется вторым сегментом.
SAFE_GIT_LEAD='^git[[:space:]]+(commit|add|status|log|show|diff|grep|tag|fetch|remote|branch|stash[[:space:]]+list|config)([[:space:]]|$)'

# Префиксы, не меняющие сути сегмента: пробелы, sudo с флагами, env-присваивания.
LEAD_SPACE_RE='^[[:space:]]+'
SUDO_PREFIX_RE='^sudo[[:space:]]+(-[a-zA-Z]+[[:space:]]+)*'
ENV_PREFIX_RE='^([a-z_][a-z0-9_]*=[^[:space:]]*[[:space:]]+)+'

# ── Время — часть контракта замка ─────────────────────────────────────────────
# Хук, не уложившийся в таймаут движка, прерывается, и команда выполняется БЕЗ вердикта:
# для движка это «разрешаю». До 26.09.2026 разбор сегментов порождал на каждый сегмент
# полтора десятка процессов (`printf | grep` на каждое правило), а в Git Bash на Windows
# процесс стоит десятки миллисекунд — замок тратил 17–60 с на обычную команду при таймауте
# 15 с. В журналах одной машины — 99 прерываний за 18–26.09, среди них команда с
# `rm -rf` по пути в переменной, которую замок, успей он, заблокировал бы. Молчание
# выглядело как «команда чистая».
#
# Два слоя защиты:
#   1) разбор сегментов идёт встроенным `=~` bash, без единого порождённого процесса —
#      проверяется тестом по тексту цикла (секция [8]), а не замером: на быстрой машине
#      старый код тоже уложился бы в срок;
#   2) свой бюджет времени меньше таймаута движка: не успел — отказываю сам (fail-closed),
#      а не жду, пока движок меня оборвёт и пропустит команду.
# Переменная окружения может бюджет только УМЕНЬШИТЬ (для теста этой ветки), не увеличить.
HOOK_BUDGET=10
if [[ "${RED_GUARD_BUDGET:-}" =~ ^[0-9]+$ ]] && (( RED_GUARD_BUDGET < HOOK_BUDGET )); then
  HOOK_BUDGET="$RED_GUARD_BUDGET"
fi

# ── ПРОВЕРКА ЦЕЛИКОМ: исполняется в фоне под сторожем времени (конец файла) ────
# Тело функции нарочно без отступа: внутри heredoc с терминатором в первой колонке и
# маркеры цикла, по которым его находит тест (секция [8]).
proverit() {
RAW="$(cat)"
CMD="$(json_get tool_input.command || true)"
if [ -z "${CMD:-}" ]; then
  # Команду прочитать не удалось — ищем опасные паттерны прямо в сыром stdin.
  # Ложное срабатывание безопаснее пропуска необратимой операции.
  CMD="$RAW"
fi

LOWER="$(printf '%s' "$CMD" | tr '[:upper:]' '[:lower:]')"
# Продолжение строки (обратная косая + перевод строки) оболочка склеивает — склеиваем и мы,
# до резки на сегменты: иначе `rm \<перевод>-rf /opt` распадался на «rm \» и «-rf /opt», и ни
# одна часть не была опасной (красная команда 19.10).
LOWER="${LOWER//$'\\\r\n'/}"
LOWER="${LOWER//$'\\\n'/}"
# Команда сама переназначает «временные» переменные — им в путях не доверяем (TMPVAR_WORD_RE).
TMPVAR_TAINTED=""
[[ $LOWER =~ $TMPVAR_WORD_RE ]] && TMPVAR_TAINTED=1
HIT=""
# Текст без кавычек и обратных косых — для опознания опасного: `r"m"`, `rm""`, `r\m` оболочка
# читает как rm, а шаблоны искали буквальное «rm» (красная команда 19.10).
LNORM="${LOWER//\"/}"; LNORM="${LNORM//\'/}"; LNORM="${LNORM//\\/}"
[[ $LNORM =~ $RM_VAR_RE ]] && HIT="$RM_VAR_RE"
OVER_BUDGET=""
# ── НАЧАЛО РАЗБОРА СЕГМЕНТОВ: внутри — только встроенные средства bash ─────────
while IFS= read -r seg; do
    if (( SECONDS >= HOOK_BUDGET )); then OVER_BUDGET=1; break; fi
    probe="$seg"
    [[ $probe =~ $LEAD_SPACE_RE ]] && probe="${probe:${#BASH_REMATCH[0]}}"
    [[ $probe =~ $SUDO_PREFIX_RE ]] && probe="${probe:${#BASH_REMATCH[0]}}"
    [[ $probe =~ $ENV_PREFIX_RE ]] && probe="${probe:${#BASH_REMATCH[0]}}"
    [ -z "$probe" ] && continue
    # Пропуск чтения и git-текста — только без подстановки команды: внутри `$(…)` и обратных
    # кавычек исполняется что угодно, и `echo $(…)` или `git commit -m "$(…)"` с удалением
    # внутри проходили замок целиком (проба 19.10.2026). Сегмент с подстановкой проверяется
    # правилами как обычный: безобидное (`echo "$(date)"`) по-прежнему проходит.
    if ! [[ $probe =~ $SUBST_RE ]]; then
        [[ $probe =~ $READONLY_LEAD ]] && continue   # чтение — не красная зона
        [[ $probe =~ $SAFE_GIT_LEAD ]] && continue   # git-текст, не операция
    fi
    # git rm без ключа силы и без подстановки команды — обратимо (см. GIT_RM_LEAD).
    if [[ $probe =~ $GIT_RM_LEAD ]] && ! [[ $probe =~ $FORCE_OPT_RE ]] \
       && ! [[ $probe =~ $SUBST_RE ]]; then
        continue
    fi
    # Опасное опознаётся по сегменту без кавычек и обратных косых (см. LNORM); исключение
    # «уборка временного» ниже разбирает исходный сегмент — пути Windows с «\» целы.
    pnorm="${probe//\"/}"; pnorm="${pnorm//\'/}"; pnorm="${pnorm//\\/}"
    for re in "${RED_PATTERNS[@]}"; do
        if [[ $pnorm =~ $re ]]; then
            # Исключение «уборка временного» действует В ГРАНИЦАХ ЭТОГО СЕГМЕНТА, не всей
            # строки. Раньше оно проверялось глобально и стоило двух ошибок сразу:
            #   ложный блок — `ls /opt/apps; rm -rf /tmp/x` рвался из-за чтения по соседству;
            #   ложный пропуск — `rm -rf /tmp/x && docker volume rm pgdata` проходил ЦЕЛИКОМ,
            #   потому что первый же сегмент объявлял безопасной всю команду.
            # Прощается только сам сегмент; остальные проверяются дальше как обычно.
            # И только если КАЖДЫЙ путь этого rm — во временном каталоге (TEMP_PATH_RE).
            if [[ $probe =~ $SAFE_RM_RE ]]; then
                rm_hit="${BASH_REMATCH[0]}"
                if ! [[ $probe =~ $TRAVERSAL_RE ]] && ! [[ $probe =~ $PROD_PATH_RE ]]; then
                    rm_pre="${probe%%"$rm_hit"*}"
                    rm_rest="${probe:${#rm_pre}+2}"
                    all_tmp=1; npaths=0; rd_next=""
                    while [[ $rm_rest =~ $TOKEN_RE ]]; do
                        tok="${BASH_REMATCH[1]}"
                        rm_rest="${rm_rest:${#BASH_REMATCH[0]}}"
                        tok="${tok//\"/}"
                        tok="${tok//\'/}"
                        [ -z "$tok" ] && continue
                        # Подстановка внутри слова исполняет что угодно — такое слово не временное.
                        if [[ $tok =~ $SUBST_RE ]]; then all_tmp=0; break; fi
                        # Слово после знака перенаправления — его цель, а не путь для rm.
                        if [ "$rd_next" = "in" ]; then rd_next=""; continue; fi
                        if [ "$rd_next" = "out" ]; then
                            rd_next=""
                            if [[ $tok =~ $SAFE_REDIR_RE ]] || [[ $tok =~ $TEMP_PATH_RE ]]; then continue; fi
                            all_tmp=0; break
                        fi
                        if [[ $tok =~ $REDIR_RE ]]; then
                            rd_to="${tok:${#BASH_REMATCH[0]}}"
                            if [ "${BASH_REMATCH[1]}" = "<" ]; then
                                [ -z "$rd_to" ] && rd_next="in"
                                continue
                            fi
                            if [ -z "$rd_to" ]; then rd_next="out"; continue; fi
                            if [[ $rd_to =~ $SAFE_REDIR_RE ]] || [[ $rd_to =~ $TEMP_PATH_RE ]]; then continue; fi
                            all_tmp=0; break
                        fi
                        [[ $tok == -* ]] && continue
                        (( npaths += 1 ))
                        if ! [[ $tok =~ $TEMP_PATH_RE ]]; then all_tmp=0; break; fi
                        if [[ $tok == \$* ]] && [ -n "$TMPVAR_TAINTED" ]; then all_tmp=0; break; fi
                    done
                    if (( all_tmp )) && (( npaths > 0 )); then
                        continue 2
                    fi
                fi
            fi
            HIT="$re"; break 2
        fi
    done
# ── КОНЕЦ РАЗБОРА СЕГМЕНТОВ ───────────────────────────────────────────────────
done <<EOF
$(printf '%s' "$LOWER" | sed -E 's/(\|\||&&|;|\||&|\n)/\n/g')
EOF

if [ -n "$OVER_BUDGET" ]; then
  deny "🔴 ЗАМОК КРАСНОЙ ЗОНЫ НЕ УСПЕЛ ПРОВЕРИТЬ КОМАНДУ за ${HOOK_BUDGET} с — блокирую (fail-closed).

Прерванный по таймауту замок движок читает как «разрешаю», поэтому непроверенное
не выпускаю. Команда не признана опасной — она просто не разобрана до конца.
Агент: повтори вызов; повторяется — раздели команду на несколько вызовов покороче."
fi

[ -z "$HIT" ] && exit 0

# ── Ищем подтверждение оператора в транскрипте сессии ─────────────────────────
SESSION_ID="$(json_get session_id || true)"
CWD="$(json_get cwd || true)"
[ -z "${CWD:-}" ] && CWD="$PWD"

TRANSCRIPT="$(json_get transcript_path || true)"
if [ -z "${TRANSCRIPT:-}" ] || [ ! -f "${TRANSCRIPT:-}" ]; then
  # Собираем путь сами: ~/.claude/projects/<slug>/<session>.jsonl,
  # slug = cwd с заменой не-буквенно-цифровых символов на «-» (канон Claude Code).
  SLUG="$(printf '%s' "$CWD" | sed 's/[^a-zA-Z0-9]/-/g')"
  TRANSCRIPT="$HOME/.claude/projects/$SLUG/${SESSION_ID:-}.jsonl"
fi

DENY_MSG="🔴 КРАСНАЯ ЗОНА — операция заблокирована замком (ADR-0022, конституция C.3).

Команда: ${CMD}

Необратимая операция выполняется только после явного подтверждения оператора.
Агент: пройди процедуру §6.3 (ASSESS → PROPOSE с «⚠️ ЧТО ТЕРЯЕМ» и «⚠️ КОПИЯ» →
EXECUTE → VERIFY) и попроси оператора написать СВОИМИ РУКАМИ:

подтверждаю <что именно делаем>, беру риск на себя, бэкап проверен

Пока этой фразы нет в сообщениях оператора — команда не выполнится.
Обойти нельзя: фраза ищется в репликах оператора, агент их не пишет."

if [ ! -f "$TRANSCRIPT" ]; then
  deny "$DENY_MSG

(Транскрипт сессии не найден: $TRANSCRIPT — подтверждение проверить нечем, поэтому блокирую.)"
fi

# Достаём последние CONFIRM_WINDOW реплик оператора и ищем в них фразу.
FOUND=""
if command -v python3 >/dev/null 2>&1; then
  FOUND="$(python3 -c '
import sys, json, re
path, window, re1, re2 = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
msgs = []
try:
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            try:
                rec = json.loads(line)
            except Exception:
                continue
            if rec.get("type") != "user":
                continue
            # Отсекаем ВСЁ, что лишь выглядит репликой оператора (иначе фраза
            # подтверждения, лежащая в файле/скилле/выводе команды, открыла бы замок —
            # prompt injection, конституция C.11). Проверено на реальном транскрипте:
            #   isMeta:true        — вставки движка (тексты скиллов, caveat-блоки)
            #   sourceToolUseID    — контент, порождённый вызовом инструмента
            #   isSidechain:true   — реплики внутри субагента, не оператор
            if rec.get("isMeta") or rec.get("sourceToolUseID") or rec.get("isSidechain"):
                continue
            m = rec.get("message") or {}
            if m.get("role") != "user":
                continue
            c = m.get("content")
            if isinstance(c, list):
                # Реплика оператора — только текстовые блоки; tool_result сюда не считаем,
                # иначе вывод команды мог бы «подтвердить» сам себя.
                if any(b.get("type") == "tool_result" for b in c if isinstance(b, dict)):
                    continue
                c = " ".join(b.get("text", "") for b in c if isinstance(b, dict) and b.get("type") == "text")
            if not isinstance(c, str) or not c.strip():
                continue
            # Служебные обёртки слэш-команд и их вывод — тоже не голос оператора.
            if c.lstrip().startswith(("<command-name>", "<local-command-", "<command-message>",
                                      "<system-reminder>", "Base directory for this skill")):
                continue
            msgs.append(c)
except Exception:
    sys.exit(2)
for text in msgs[-window:]:
    low = text.lower()
    if re.search(re1, low) and re.search(re2, low):
        print("yes")
        break
' "$TRANSCRIPT" "$CONFIRM_WINDOW" "$CONFIRM_RE" "$CONFIRM_RE2" 2>/dev/null)" || FOUND=""
else
  # Без python3 — грубее: хвост файла, отбросив вставки движка и вывод инструментов.
  TAIL="$(grep '"role":"user"' "$TRANSCRIPT" 2>/dev/null \
          | grep -v '"tool_result"' | grep -v '"isMeta":true' \
          | grep -v '"sourceToolUseID"' | grep -v '"isSidechain":true' \
          | tail -n "$CONFIRM_WINDOW")"
  if printf '%s' "$TAIL" | grep -iq "$CONFIRM_RE" && printf '%s' "$TAIL" | grep -iq "$CONFIRM_RE2"; then
    FOUND="yes"
  fi
fi

[ "$FOUND" = "yes" ] && exit 0
deny "$DENY_MSG"
}
# ── КОНЕЦ ПРОВЕРКИ ────────────────────────────────────────────────────────────

# ── Сторож времени: бюджет покрывает ВЕСЬ замок, а не только цикл ──────────────
# Разбор 06.10.2026. Бюджет до этого проверялся только внутри цикла по сегментам, а до
# цикла замок уже порождал процессы: `cat` на вход, `python3` на разбор JSON, `tr`, `sed`.
# 03.10 на машине оператора (Windows, параллельно работали несколько агентов) замок шёл
# 36,5 с при таймауте движка 15 с — движок оборвал его и выполнил команду без вердикта.
# Та же команда в спокойную минуту проходит за 0,6 с: дефект не в разборе, а в том, что
# время до цикла не считал никто. Особенно дорог `python3`: на Windows это часто заглушка
# Microsoft Store (`WindowsApps\python3`), её запуск — сотни миллисекунд даже в покое.
#
# Устройство: вся проверка (`proverit`) идёт в фоне, основная часть ждёт её встроенным
# `read -t` и сама не порождает ни одного процесса. Не дождалась — печатает отказ
# встроенным `printf` (не python: под той же нагрузкой и он может не успеть) и выходит.
# Фоновая проверка гасится `kill`. В Git Bash сигнал доходит до неё, только когда её
# текущая программа (тот же зависший python3) вернёт управление, — поэтому хвост может
# пожить несколько секунд. Движку он не мешает, пока не держит открытыми его трубы:
# stdout фоновой части — своя труба к сторожу, а stderr заменён насовсем через
# `exec 2>/dev/null`. Не `proverit 2>/dev/null`: перенаправление на вызов функции bash
# делает, сохранив копию прежнего stderr у себя, — труба движка оставалась открытой, пока
# висела программа, и движок ждал бы её (поймано тестом 06.10.2026: 6,5 с вместо 2).
over_budget() {
  printf '%s\n' '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"🔴 ЗАМОК КРАСНОЙ ЗОНЫ НЕ УСПЕЛ ПРОВЕРИТЬ КОМАНДУ за '"$HOOK_BUDGET"' с — блокирую (fail-closed).\n\nПрерванный по таймауту замок движок читает как «разрешаю», поэтому непроверенное не выпускаю. Команда не признана опасной — проверка не завершилась: длинная команда или занятая машина.\nАгент: повтори вызов; повторяется — раздели команду на несколько вызовов покороче."}}'
  exit 0
}
#
# Переносимость (bash 3.2 — системный на macOS): `$!` после `<( )` задан только с bash 4.4,
# а под `set -u` пустой `$!` обрывает скрипт без вывода — то есть «разрешаю»; отличать
# «время вышло» от «конец данных» по коду `read -t` (>128) bash умеет только с 4.0. Поэтому
# номер берётся как `${!:-}`, а завершение проверки узнаётся по метке конца, которую фоновая
# часть печатает последней — после вложенной `( proverit )`, чьи `exit` её не отменяют.
# Нет метки — проверка не дошла до конца (время вышло или её оборвали): отказ.
KONETS_PROVERKI='__KONETS_PROVERKI_ZAMKA__'
OSTALOS=$(( HOOK_BUDGET - SECONDS ))
(( OSTALOS > 0 )) || over_budget
exec 3< <(exec 2>/dev/null; ( proverit ); printf '%s' "$KONETS_PROVERKI")
PROVERKA_PID="${!:-}"
VERDIKT=""
IFS= read -r -d '' -t "$OSTALOS" VERDIKT <&3
case "$VERDIKT" in
  *"$KONETS_PROVERKI") VERDIKT="${VERDIKT%"$KONETS_PROVERKI"}" ;;
  *) [ -n "$PROVERKA_PID" ] && kill "$PROVERKA_PID" 2>/dev/null
     over_budget ;;
esac
[ -n "$VERDIKT" ] && printf '%s' "$VERDIKT"
exit 0
